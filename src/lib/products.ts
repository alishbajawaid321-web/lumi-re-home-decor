export const getProduct = (id: string): Product | undefined =>
  PRODUCTS.find((p) => p.id === id);

export const relatedProducts = (product: Product, limit = 4): Product[] =>
  PRODUCTS.filter((p) => p.id !== product.id)
    .map((p) => {
      let score = 0;
      if (p.category === product.category) score += 5;
      if (p.subcategory === product.subcategory) score += 3;
      score += p.rooms.filter((r) => product.rooms.includes(r)).length;
      score += p.tags.filter((t) => product.tags.includes(t)).length;
      if (p.style === product.style) score += 1;
      return { p, score };
    })
    .sort((a, b) => b.score - a.score || b.p.popularity - a.p.popularity)
    .slice(0, limit)
    .map((x) => x.p);

export const searchProducts = (query: string, limit?: number): Product[] => {
  const q = query.trim().toLowerCase();
  if (!q) return [];
  const terms = q.split(/\s+/);
  const results = PRODUCTS.map((p) => {
    const haystack = [
      p.name,
      categoryName(p.category),
      p.subcategory,
      p.material,
      p.style,
      p.color,
      ...p.tags,
      ...p.rooms.map(roomName),
    ]
      .join(" ")
      .toLowerCase();
    const score = terms.reduce(
      (acc, t) => acc + (haystack.includes(t) ? (p.name.toLowerCase().includes(t) ? 3 : 1) : 0),
      0,
    );
    return { p, score };
  })
    .filter((x) => x.score > 0)
    .sort((a, b) => b.score - a.score || b.p.popularity - a.p.popularity)
    .map((x) => x.p);
  return limit ? results.slice(0, limit) : results;
};

