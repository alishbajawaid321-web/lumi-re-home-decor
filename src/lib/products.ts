/** Budget decorator: greedily builds the richest collection under a budget. */
export function buildBudgetCollection(budget: number, roomSlug: string): Product[] {
  const pool = productsByRoom(roomSlug)
    .filter((p) => p.inStock)
    .sort((a, b) => b.rating * b.popularity - a.rating * a.popularity);

  const picked: Product[] = [];
  const usedCategories = new Set<string>();
  let total = 0;

  // First pass: one hero piece per category, largest first.
  for (const p of [...pool].sort((a, b) => finalPrice(b) - finalPrice(a))) {
    if (usedCategories.has(p.category)) continue;
    if (total + finalPrice(p) > budget) continue;
    picked.push(p);
    usedCategories.add(p.category);
    total += finalPrice(p);
  }
  // Second pass: fill remaining budget with smaller accents.
  for (const p of [...pool].sort((a, b) => finalPrice(a) - finalPrice(b))) {
    if (picked.some((x) => x.id === p.id)) continue;
    if (total + finalPrice(p) > budget) continue;
    picked.push(p);
    total += finalPrice(p);
    if (picked.length >= 10) break;
  }
  return picked.sort((a, b) => finalPrice(b) - finalPrice(a));
}

